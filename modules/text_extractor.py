def extract_ingredients_from_text(raw_text):
    """
    ฟังก์ชันหลักที่คนที่ 6 เรียกใช้เพื่อสกัดคำวัตถุดิบจากข้อความ
    คืนค่า dict ที่มี:
    - extracted_ingredients: list วัตถุดิบมาตรฐาน 12 ชนิด
    - tokens_found: คำที่ระบบจับได้
    - raw_input: ข้อความต้นฉบับ
    """
    if not raw_text or not isinstance(raw_text, str):
        return {
            "success": True,
            "raw_input": "",
            "extracted_ingredients": [],
            "tokens_found": []
        }

    cleaned = raw_text.strip().lower()
    
    # ลบตัวเลข (เช่น 2 ฟอง, 3 ขีด)
    cleaned = re.sub(r'\d+', ' ', cleaned)
    
    # ลบสัญลักษณ์พิเศษ
    cleaned = re.sub(r'[,./?!\-+~@#$%^&*()_=\[\]{};:\'"]', ' ', cleaned)

    found_ingredients = set()
    tokens_found = []

    # วิธีสกัด: สแกนจับคู่คำยาวไปคำสั้น (Longest Match First)
    sorted_synonyms = sorted(SYNONYM_DICT.keys(), key=lambda x: len(x), reverse=True)
    
    for syn in sorted_synonyms:
        if syn in cleaned:
            canonical_name = SYNONYM_DICT[syn]
            found_ingredients.add(canonical_name)
            tokens_found.append({"keyword": syn, "normalized_to": canonical_name})
            # ลบคำที่เจอออกจากข้อความเพื่อป้องกันการจับซ้ำ
            cleaned = cleaned.replace(syn, ' ')

    return {
        "success": True,
        "raw_input": raw_text,
        "extracted_ingredients": list(found_ingredients),
        "tokens_found": tokens_found,
        "count": len(found_ingredients)
    }
